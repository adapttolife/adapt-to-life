-- Signed waivers: drop the retired r2_key column from the live table.
--
--   cfrun bash -c "CLOUDFLARE_ACCOUNT_ID=<Adapt To Life account> npx wrangler d1 execute atl-waivers --remote \
--     --file schema/migrations/2026-11-23-waivers-drop-r2-key.sql"
--
-- The June 2026 table stored each PDF in R2 and kept its key in
-- `r2_key TEXT NOT NULL` (no default). The Sept 14 change that retired R2
-- removed the column from schema/waivers.sql and from the capture INSERT, but
-- no migration removed it from the live table, so every signing on both
-- waivers failed with "NOT NULL constraint failed: waivers.r2_key" until this
-- ran on Nov 23 2026. The worker never reads or writes r2_key.
--
-- Safe to drop: the column has no index, trigger or view on it. When this ran,
-- the table held three releases (June 27 to 29), each archived to Drive; their
-- keys were `waivers/atl/<date>/<id>.pdf`, derivable from the row, and a copy
-- of those rows was kept before the drop. D1 Time Travel can also restore the
-- database to any minute in the last 30 days.
--
-- Not idempotent (SQLite has no DROP COLUMN IF EXISTS): run it once.
-- scripts/check-d1-schema.mjs confirms the live table matches schema/waivers.sql.
ALTER TABLE waivers DROP COLUMN r2_key;
