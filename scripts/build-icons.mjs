#!/usr/bin/env node
// scripts/build-icons.mjs: pull every meaning in data/icons.mjs from its
// open-source package and write the two things the site uses:
//
//   scripts/lib/icons.mjs     the drawings plus icon() and logo(), imported by
//                             the page generators (committed, so the deploy
//                             build never rewrites a tracked file)
//   the pages and scripts     every dictionary icon on a public page redrawn
//                             (scripts/lib/apply-icons.mjs), and the marked
//                             icons:start/end blocks in public/js/campaigns.js,
//                             public/js/add-to-calendar.js and src/css/site.css
//   brand/icons/sheet.html    every meaning in every style at 18, 28 and 56px
//                             on both page colors: open it before you ship a
//                             new icon, the way the custom set should have been
//
//   npm run icons            write both
//   npm run icons -- --check fail if either is out of date (run by the tests)
//
// The drawings come from the @iconify-json packages (one JSON file per
// library, devDependencies pinned in package.json), so pages carry plain
// inline SVG and load no icon script.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SOURCES, PH_WEIGHTS, MEANINGS, LOGOS } from "../data/icons.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const CHECK = process.argv.includes("--check");

const sets = {};
function set(src) {
  if (!sets[src]) {
    const pkg = SOURCES[src].pkg;
    sets[src] = { json: require(`${pkg}/icons.json`), version: require(`${pkg}/package.json`).version };
  }
  return sets[src];
}

function draw(src, name) {
  const { json } = set(src);
  let icon = json.icons[name], key = name;
  if (!icon && json.aliases?.[name]) { key = json.aliases[name].parent; icon = json.icons[key]; }
  if (!icon) throw new Error(`${SOURCES[src].name} has no icon "${name}"`);
  const w = icon.width ?? json.width ?? 16, h = icon.height ?? json.height ?? 16;
  return { vb: `0 0 ${w} ${h}`, body: icon.body.replace(/\s+/g, " ").trim() };
}

const icons = {};
for (const [meaning, m] of Object.entries(MEANINGS)) {
  icons[meaning] = { src: m.src, icon: m.icon, means: m.means, styles: {} };
  if (m.src === "ph") {
    for (const w of PH_WEIGHTS) icons[meaning].styles[w] = draw("ph", w === "regular" ? m.icon : `${m.icon}-${w}`);
  } else {
    icons[meaning].styles.regular = draw(m.src, m.icon);
  }
}
const logos = {};
for (const [name, l] of Object.entries(LOGOS)) logos[name] = { means: l.means, ...draw(l.src, l.icon) };

const versions = Object.fromEntries(Object.keys(sets).sort().map((s) => [SOURCES[s].pkg, sets[s].version]));

const lib = `// GENERATED by scripts/build-icons.mjs from data/icons.mjs. Do not edit;
// change the dictionary and run \`npm run icons\`.
//
// Drawn from: ${Object.entries(versions).map(([p, v]) => `${p}@${v}`).join(", ")}.
// Phosphor and Hugeicons are MIT, Material Symbols is Apache 2.0, Simple Icons is CC0.

export const ICONS = ${JSON.stringify(icons, null, 1)};

export const LOGOS = ${JSON.stringify(logos, null, 1)};

// A meaning as inline SVG. style is one of regular, duotone, bold, fill;
// a source with one style (Material, Hugeicons) uses it for every style.
// data-icon names the meaning so the tests can check every icon on a page
// came from here and was not pasted in by hand.
export function icon(meaning, style = "regular", cls = "ix-svg") {
  const m = ICONS[meaning];
  if (!m) throw new Error("no meaning " + meaning + " in data/icons.mjs");
  const d = m.styles[style] || m.styles.regular;
  const st = m.styles[style] ? style : "regular";
  return \`<svg class="\${cls}" viewBox="\${d.vb}" fill="currentColor" aria-hidden="true" focusable="false" data-icon="\${meaning}" data-style="\${st}">\${d.body}</svg>\`;
}

// A platform's own logo, for tool chips and social links only.
export function logo(name, cls = "ix-svg") {
  const l = LOGOS[name];
  if (!l) throw new Error("no logo " + name + " in data/icons.mjs");
  return \`<svg class="\${cls}" viewBox="\${l.vb}" fill="currentColor" aria-hidden="true" focusable="false" data-logo="\${name}">\${l.body}</svg>\`;
}
`;

const svg = (d, s) => `<svg width="${s}" height="${s}" viewBox="${d.vb}" fill="currentColor" aria-hidden="true">${d.body}</svg>`;
const row = (label, sub, styles) => `<tr><th>${label}<small>${sub}</small></th>${styles.map((d) =>
  `<td class="l">${d ? [18, 28, 56].map((s) => svg(d, s)).join(" ") : ""}</td><td class="k">${d ? [18, 28, 56].map((s) => svg(d, s)).join(" ") : ""}</td>`).join("")}</tr>`;
const sheet = `<!doctype html>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Adapt To Life symbols</title>
<!-- GENERATED by scripts/build-icons.mjs. Every meaning in data/icons.mjs, in every style, at 18/28/56px. -->
<style>
body{font:15px/1.5 "Sofia Sans",system-ui,sans-serif;background:#F9F7F2;color:#1A1A1A;margin:24px}
h1{font-size:26px;margin:0 0 4px} p{margin:0 0 18px;color:#3C382F;max-width:70ch}
.scroll{overflow-x:auto} table{border-collapse:separate;border-spacing:0 6px}
th{text-align:left;padding:6px 14px;font-weight:800;white-space:nowrap} th small{display:block;font-weight:400;color:#6A675E;max-width:30ch;white-space:normal}
thead th{font-size:13px;color:#6A675E;font-weight:700}
td{padding:8px 12px;white-space:nowrap} td.l{background:#FFFDF8;color:#C63F22} td.k{background:#0C0C0E;color:#FF5C39}
svg{vertical-align:middle}
</style>
<h1>Adapt To Life symbols</h1>
<p>One meaning, one picture, everywhere. Pages ask for the meaning; data/icons.mjs says which drawing it is. Duotone is a section's symbol, regular is chips and row details, bold is where you are, fill is selected. Logos only ever mean a tool or platform.</p>
<p>Drawn from ${Object.entries(versions).map(([p, v]) => `${p} ${v}`).join(", ")}.</p>
<div class="scroll"><table>
<thead><tr><th>Meaning</th>${PH_WEIGHTS.map((w) => `<th colspan="2">${w}</th>`).join("")}</tr></thead>
${Object.entries(icons).map(([k, m]) => row(`${k} <span style="font-weight:400;color:#6A675E">· ${SOURCES[m.src].name} ${m.icon}</span>`, m.means,
  PH_WEIGHTS.map((w) => m.styles[w] || (w === "regular" ? m.styles.regular : null)))).join("\n")}
</table></div>
<h2>Logos</h2>
<div class="scroll"><table>${Object.entries(logos).map(([k, l]) => row(k, l.means, [l])).join("\n")}</table></div>
`;

const LIB = join(ROOT, "scripts/lib/icons.mjs");
const out = [
  [LIB, lib],
  [join(ROOT, "brand/icons/sheet.html"), sheet],
];

// The registry must be current before the pages can be redrawn from it.
if (!CHECK) { writeFileSync(LIB, lib); }
const reg = await import(pathToFileURL(LIB).href + "?" + Date.now());
const { applyIcons } = await import(pathToFileURL(join(ROOT, "scripts/lib/apply-icons.mjs")).href + "?" + Date.now());

// Marked blocks in scripts and the stylesheet.
const block = (text, body, path) => {
  const re = /(\/\* icons:start[^*]*\*\/\n)[\s\S]*?(\s*\/\* icons:end \*\/)/;
  if (!re.test(text)) throw new Error(`no icons:start/end block in ${path}`);
  return text.replace(re, (_, a, b) => a + body + b);
};
const sized = (svg) => svg.replace("<svg ", '<svg width="16" height="16" ');
const jsMap = (pairs) => "  var ICON = {\n" + pairs.map(([k, v]) => `    ${k}: ${JSON.stringify(v)}`).join(",\n") + "\n  };";
const jsFiles = {
  "public/js/campaigns.js": jsMap([["time", sized(reg.icon("time", "regular", "evc-svg"))], ["place", sized(reg.icon("place", "regular", "evc-svg"))],
    ["group", sized(reg.icon("community", "regular", "evc-svg"))], ["cal", sized(reg.icon("event", "regular", "evc-svg"))],
    ["arrow", reg.icon("arrow", "bold")], ["external", reg.icon("external", "bold")]]),
  "public/js/add-to-calendar.js": jsMap([["apple", reg.logo("apple", "atc-svg")], ["google", reg.logo("googlecalendar", "atc-svg")], ["outlook", reg.logo("outlook", "atc-svg")]]),
};
for (const [rel, body] of Object.entries(jsFiles)) {
  const path = join(ROOT, rel);
  out.push([path, block(readFileSync(path, "utf8"), body, rel)]);
}
const masks = Object.entries(icons).filter(([k]) => MEANINGS[k].css).map(([k, m]) => {
  const d = m.styles.bold || m.styles.regular;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${d.vb}">${d.body}</svg>`;
  return `  --icon-${k}: url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}");`;
});
const css = join(ROOT, "src/css/site.css");
out.push([css, block(readFileSync(css, "utf8"), ":root{\n" + masks.join("\n") + "\n}", "src/css/site.css")]);

// Every hand-written public page (the hero lab is internal, so it is left as is).
const PUB = join(ROOT, "public");
const pageFiles = readdirSync(PUB).filter((f) => f.endsWith(".html") && !f.startsWith("hero-")).map((f) => join(PUB, f))
  .concat(readdirSync(join(PUB, "volunteer")).filter((f) => f.endsWith(".html")).map((f) => join(PUB, "volunteer", f)));
for (const path of pageFiles) out.push([path, applyIcons(readFileSync(path, "utf8"))]);
let stale = 0;
for (const [path, text] of out) {
  if (CHECK) {
    let cur = ""; try { cur = readFileSync(path, "utf8"); } catch {}
    if (cur !== text) { stale++; console.error(`out of date: ${path.replace(ROOT + "/", "")}`); }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
if (CHECK && stale) { console.error("build-icons --check FAILED. Run `npm run icons` and commit the result."); process.exit(1); }
console.log(CHECK ? `build-icons --check ok (${Object.keys(icons).length} meanings, ${Object.keys(logos).length} logos, ${pageFiles.length} pages)` : `wrote the registry, sheet, scripts, stylesheet masks and ${pageFiles.length} pages (${Object.keys(icons).length} meanings, ${Object.keys(logos).length} logos)`);
